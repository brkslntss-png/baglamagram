const DILLER = Object.keys(METINLER);
let dil = 'en';

/** Sistem dillerinden ilk desteklenenini seçer (uygulama hazır olduktan sonra çağrılır). */
function dilSec(tercihler) {
  for (const t of tercihler || []) {
    const kisa = String(t).slice(0, 2).toLowerCase();
    if (DILLER.includes(kisa)) { dil = kisa; return dil; }
  }
  dil = 'en';
  return dil;
}

/** Metin; {ad} yer tutucuları doldurulur. Eksik çeviride İngilizcesi, o da yoksa anahtarın kendisi. */
function metin(anahtar, degerler) {
  let s = METINLER[dil][anahtar] ?? METINLER.en[anahtar] ?? anahtar;
  if (degerler) for (const [k, v] of Object.entries(degerler)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

module.exports = { metin, dilSec, dil: () => dil, METINLER };
